"""Original teaching beats for each of the 89 additional course days.

Each record contains a complete example and its expected result, why the
concept matters, a concrete model, execution trace and common error. Keep
pedagogical text here; the renderer never guesses a lesson from a title.
"""

from dataclasses import dataclass, field
import re


@dataclass(frozen=True)
class Day:
    number: int
    slug: str
    title: str
    anchor: str
    code: str
    output: str
    focus: str
    wrong: str
    why: str
