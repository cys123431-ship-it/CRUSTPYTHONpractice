    change: str = "예시의 첫 입력 값을 하나"
    task: str = "같은 입력을 받아 같은 결과를 만드는"

    @property
    def buggy(self) -> str:
        return self.code.replace(self.focus, self.wrong, 1)

    @property
    def modified(self) -> tuple[str, str]:
        overrides = {
            26: ('minutes[1]', 'minutes[2]'),
            62: ('["B"]["prev"]', '["A"]["next"]'),
            65: ('key = 10', 'key = 9'),
            47: ('10\\n20\\n', '10\\n20\\n30\\n'),
            55: ('assert total([10, 20]) == 30', 'assert total([11, 20]) == 31'),
            68: ('print(edges["A"])', 'print(edges["B"])'),
            69: ('print(sorted(seen))', 'print(len(seen))'),
            81: ('dfs("A")', 'dfs("B")'),
            83: ('fields[3]', 'fields[2]'),
            85: ('변수,30,pass', '변수,31,pass'),
            92: ('assert total == 60', 'assert total == 60\nassert len(sessions) == 3'),
        }
        if self.number == 56:
            return (self.code.replace('let s=Session{minutes:30};\n    assert_eq!(s.minutes,30);',
                                      'let s=Session{minutes:31};\n    assert_eq!(s.minutes,31);'),
                    '초기 minutes 값과 assert_eq!의 기대값을 함께 30에서 31로')
        if self.number == 89:
            return self.code.replace('let raw = "30";', 'let raw = "31";'), '입력 문자열 30을 31로'
        if self.number in overrides:
            before, after = overrides[self.number]
            return self.code.replace(before, after, 1), f"{before!r}을 {after!r}로"
        strings = [m.span() for m in re.finditer(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', self.code)]
        number = next((m for m in re.finditer(r"(?<![A-Za-z_0-9])(\d+)(?![A-Za-z_0-9])", self.code)
                       if not any(start <= m.start() < end for start, end in strings)
                       and not re.search(r"return\s+0\s*;\s*$", self.code[max(0, m.start()-8):m.end()+1])), None)
        if number:
            before = number.group(1)
            after = str(int(before) + 1)
            return self.code[:number.start(1)] + after + self.code[number.end(1):], f"처음 등장하는 숫자를 {before}에서 {after}로"
        literal = re.search(r'"([^"\\]+)"', self.code)
        if literal:
            before = literal.group(1)
            after = before + "!"
            return self.code[:literal.start(1)] + after + self.code[literal.end(1):], f"첫 문자열을 {before!r}에서 {after!r}로"
        raise ValueError(f"Day {self.number} has no editable literal")


